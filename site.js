// depth cards: tilt toward the mouse, layers drift by their depth, bubbles splash out on enter
var fine = matchMedia("(hover: hover) and (pointer: fine)").matches && !matchMedia("(prefers-reduced-motion: reduce)").matches;
document.querySelectorAll(".pop").forEach(function (card) {
  var scene = card.querySelector(".depth");
  if (!scene || !fine) return;
  card.addEventListener("pointermove", function (e) {
    var r = scene.getBoundingClientRect();
    var x = Math.max(-.5, Math.min(.5, (e.clientX - r.left) / r.width - .5));
    var y = Math.max(-.5, Math.min(.5, (e.clientY - r.top) / r.height - .5));
    scene.style.setProperty("--ry", (x * 12) + "deg");
    scene.style.setProperty("--rx", (-y * 9) + "deg");
    scene.style.setProperty("--mx", x);
    scene.style.setProperty("--my", y);
  });
  card.addEventListener("pointerleave", function () {
    ["--rx", "--ry", "--mx", "--my"].forEach(function (p) { scene.style.removeProperty(p); });
  });
  card.addEventListener("pointerenter", function () {
    scene.querySelectorAll(".d-buddy, .d-coin, .d-pop.d-left, .d-pop.d-right").forEach(function (b) {
      for (var i = 0; i < 6; i++) {
        var s = document.createElement("span"), size = 6 + Math.random() * 14;
        s.className = "splash";
        s.style.cssText = "width:" + size + "px;height:" + size + "px;left:" + (b.offsetLeft + b.offsetWidth * (.2 + Math.random() * .6)) + "px;top:" + (b.offsetTop + b.offsetHeight * .3) + "px;--sx:" + ((Math.random() - .5) * 90) + "px;--sy:" + (-40 - Math.random() * 80) + "px;animation-delay:" + (Math.random() * .2) + "s";
        scene.appendChild(s);
        s.addEventListener("animationend", function () { this.remove(); });
      }
    });
  });
});

// fishing line: from Croaky's rod tip to the bobber, redrawn while the layers move
document.querySelectorAll(".depth").forEach(function (scene) {
  var rod = scene.querySelector('img[src*="-reel"]'), bob = scene.querySelector('img[src*="bobber"]');
  if (!rod || !bob) return;
  var ns = "http://www.w3.org/2000/svg", svg = document.createElementNS(ns, "svg"), path = document.createElementNS(ns, "path");
  svg.setAttribute("class", "d-line"); svg.appendChild(path); scene.insertBefore(svg, bob);
  function draw() {
    var s = scene.getBoundingClientRect(), r = rod.getBoundingClientRect(), b = bob.getBoundingClientRect();
    if (!s.width) return;
    var x1 = r.left + r.width * .97 - s.left, y1 = r.top + r.height * .37 - s.top; // rod tip
    var x2 = b.left + b.width * .5 - s.left, y2 = b.top + b.height * .04 - s.top; // top of the bobber stem
    var cx = (x1 + x2) / 2, cy = Math.max(y1, y2) + Math.abs(x2 - x1) * .12; // a little slack
    path.setAttribute("d", "M" + x1 + " " + y1 + " Q" + cx + " " + cy + " " + x2 + " " + y2);
  }
  var until = 0, running = false;
  function loop() { draw(); if (performance.now() < until) requestAnimationFrame(loop); else running = false; }
  function kick(ms) { until = Math.max(until, performance.now() + ms); if (!running) { running = true; requestAnimationFrame(loop); } }
  var card = scene.closest(".pop") || scene;
  card.addEventListener("pointermove", function () { kick(100); });
  card.addEventListener("pointerenter", function () { kick(700); });
  card.addEventListener("pointerleave", function () { kick(700); });
  [rod, bob].forEach(function (i) { if (!i.complete) i.addEventListener("load", draw); });
  addEventListener("resize", draw); addEventListener("load", draw); draw();
});

